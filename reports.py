def _validation_findings(df):
    """Scan the imported data for quality issues. Returns
    (summary_rows, sections) where summary_rows is a list of
    [check_name, issues_found, status] and sections is a list of
    (title, headers, rows) detail tables. Diagnostic only."""
    raw = df.attrs.get("raw")
    if raw is None:
        raw = pd.DataFrame()
    subject_cols = list(df.attrs.get("subject_cols") or [])
    rolls = df["_roll"].astype(str).str.strip() if "_roll" in df.columns else pd.Series([], dtype=str)
    names = df["_name"].astype(str).str.strip() if "_name" in df.columns else pd.Series([], dtype=str)
    roll_blank = rolls.apply(_blank)
    name_blank = names.apply(_blank)

    summary = []
    sections = []

    def add(check, count, headers, rows):
        status = "OK - no issues" if count == 0 else f"{count} item(s) to review"
        summary.append([check, count, status])
        if rows:
            sections.append((check, headers, rows))

    # 1a. duplicate roll numbers
    seen = {}
    dup_rows = []
    for i, r in enumerate(rolls):
        if _blank(r):
            continue
        key = r.strip()
        seen.setdefault(key, []).append(i)
    dupes = {k: v for k, v in seen.items() if len(v) > 1}
    for r, idxs in sorted(dupes.items()):
        nm = "; ".join(str(names.iloc[i]).strip() for i in idxs[:3])
        dup_rows.append([r, len(idxs),
                         ", ".join(str(i + 1) for i in idxs), nm[:60]])
    add("Duplicate roll numbers", len(dupes),
        ["Roll number", "Times used", "Rows in table", "Names (first 3)"],
        dup_rows)

    # 1b. missing roll numbers
    miss_roll = [[i + 1, str(names.iloc[i]).strip()[:40]]
                 for i in rolls.index if roll_blank.loc[i]]
    add("Rows with missing roll number", len(miss_roll),
        ["Row in table", "Name shown"], miss_roll)

    # 1c. missing names
    miss_name = [[i + 1, str(rolls.iloc[i]).strip()[:30]]
                 for i in names.index if name_blank.loc[i]]
    add("Rows with missing student name", len(miss_name),
        ["Row in table", "Roll number shown"], miss_name)

    # 1d. duplicate full rows
    dup_mask = raw.duplicated(keep=False) if len(raw) else pd.Series([], dtype=bool)
    dup_full = sorted(set(int(i) + 1 for i in raw.index[dup_mask])) if len(raw) else []
    add("Fully duplicate rows", len(dup_full), ["Row in table"],
        [[r] for r in dup_full])

    # 1e/1f/1g. per-subject checks
    oor_rows, nonnum_rows, empty_cols = [], [], []
    for col in subject_cols:
        if col not in raw.columns:
            continue
        series = raw[col]
        nums = pd.to_numeric(series, errors="coerce")
        bad = nums[(nums < 0) | (nums > 100)].dropna()
        for i, v in bad.items():
            oor_rows.append([col[:32], int(i) + 1, v,
                             str(rolls.loc[i]).strip()[:30] if i in rolls.index else ""])
        mask_nonnum = nums.isna() & ~series.apply(_blank)
        if mask_nonnum.any():
            distinct = series[mask_nonnum].astype(str).str.strip()
            for val, cnt in distinct.value_counts().head(10).items():
                nonnum_rows.append([col[:32], val[:24], int(cnt)])
        if nums.notna().sum() == 0:
            empty_cols.append([col[:40]])
    add("Marks outside 0-100", len(oor_rows),
        ["Subject", "Row in table", "Value entered", "Roll number"], oor_rows)
    add("Non-numeric entries in subject columns", len(nonnum_rows),
        ["Subject", "Entry", "Times used"],
        nonnum_rows)
    add("Subject columns with no usable marks", len(empty_cols),
        ["Subject column"], empty_cols)

    # 1h. incomplete rows (some subjects filled, some blank)
    inc_rows = []
    if subject_cols:
        for i in raw.index:
            filled, blank_n = 0, 0
            for col in subject_cols:
                if col not in raw.columns:
                    continue
                v = raw.at[i, col]
                if _blank(v):
                    blank_n += 1
                elif pd.notna(pd.to_numeric(pd.Series([v]), errors="coerce").iloc[0]):
                    filled += 1
            if filled > 0 and blank_n > 0:
                inc_rows.append([int(i) + 1,
                                 str(rolls.loc[i]).strip()[:30] if i in rolls.index else "",
                                 filled, blank_n])
    add("Rows with incomplete subject marks", len(inc_rows),
        ["Row in table", "Roll number", "Subjects filled", "Subjects blank"],
        inc_rows)

    return summary, sections


