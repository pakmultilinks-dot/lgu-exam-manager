def _blank(v) -> bool:
    """True for empty / NaN / 'nan' / 'None' cell values."""
    if v is None:
        return True
    try:
        if pd.isna(v):
            return True
    except Exception:
        pass
    return str(v).strip().lower() in ("", "nan", "none", "nat")


def _bar_chart_png(labels, values, title, xlabel="", ylabel=""):
    """Render a simple bar chart to a temp PNG file. Returns the file path.

    Caller is responsible for deleting the file when done.
    """
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        raise RuntimeError(
            "Charts need the 'matplotlib' package.\n"
            "Install it with:  pip install matplotlib")
    labels = [str(l) for l in labels]
    fig, ax = plt.subplots(figsize=(7.2, 3.4), dpi=100)
    xs = list(range(len(labels)))
    ax.bar(xs, values, color="#0D542B", edgecolor="#08331B")
    ax.set_xticks(xs)
    ax.set_xticklabels(labels, rotation=28, ha="right", fontsize=8)
    ax.set_title(title, fontsize=11, fontweight="bold", color="#0D542B")
    if xlabel:
        ax.set_xlabel(xlabel, fontsize=9)
    if ylabel:
        ax.set_ylabel(ylabel, fontsize=9)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    fig.tight_layout()
    tmp = _tempfile.NamedTemporaryFile(delete=False, suffix=".png")
    tmp.close()
    fig.savefig(tmp.name, dpi=100)
    plt.close(fig)
    return tmp.name


