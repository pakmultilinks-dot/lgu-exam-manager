def _analysis_data2(df: pd.DataFrame):
    stats = compute_stats(df)
    cgpa = pd.to_numeric(df["_cgpa"], errors="coerce").dropna()
    gl = stats.get("grade_label", "CGPA")
    summary = [
        ("Average " + gl, stats["avg_cgpa"]),
        ("Median " + gl, round(float(cgpa.median()), 2) if len(cgpa) else None),
        ("Std Deviation", round(float(cgpa.std()), 2) if len(cgpa) > 1 else None),
        ("Highest " + gl, stats["max_cgpa"]),
        ("Lowest " + gl, stats["min_cgpa"]),
    ]
    dist = stats["distribution"]
    mx = max(dist.values()) if dist and max(dist.values()) > 0 else 1
    dist_rows = [[k, v, "#" * max(1, round(v / mx * 22)) if v else ""]
                 for k, v in dist.items()]
    merit_rows = [[i + 1, m["roll"], m["name"], _fmt_cgpa(m["cgpa"])]
                  for i, m in enumerate(stats["merit"])]
    return summary, dist_rows, merit_rows, gl


