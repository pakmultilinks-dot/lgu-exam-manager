def _failing_subjects_data(df: pd.DataFrame, mapping: dict):
    """Per failed student: subjects scoring below the operator-set passing
    marks. The failed-student filter uses the source file's own Status
    values; the per-subject cutoff is the operator's rule only."""
    rule = _operator_rule(df, "passing_marks")
    subj_cols = mapping.get("subject") or []
    raw = df.attrs.get("raw")
    status = normalize_status(df["_status"])
    failed = df[status == "Fail"]
    rows = []
    for _, row in failed.iterrows():
        weak = []
        if rule is not None and raw is not None:
            for s in subj_cols:
                if s in raw.columns:
                    v = pd.to_numeric(raw.loc[row.name, s], errors="coerce")
                    if pd.notna(v) and float(v) < rule:
                        weak.append(f"{s}: {_fmt_rule(float(v))}")
        rows.append([row["_roll"], row["_name"], ", ".join(weak), len(weak)])
    return rule, len(failed), rows


