def _operator_rule(df: pd.DataFrame, key: str):
    """Return the operator-configured numeric rule, or None when not set.

    Rules come from the Settings tab only. Empty / missing / non-numeric
    means "no rule configured" - the report must not invent a cutoff.
    """
    s = (df.attrs.get("settings") or {}).get(key)
    if s is None:
        return None
    if isinstance(s, str) and not s.strip():
        return None
    try:
        return float(s)
    except (TypeError, ValueError):
        return None


def _fmt_rule(v: float) -> str:
    return "%g" % v


