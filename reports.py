def _word_stat_box(doc, items):
    """1xN summary box table for Word. items=[(label, value)]."""
    if not items:
        return
    table = doc.add_table(rows=2, cols=len(items))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    from docx.oxml.ns import qn
    for i, (label, value) in enumerate(items):
        for r_, txt, bold, sz, color in (
                (0, str(value), True, 13, LGU_GREEN),
                (1, str(label), False, 9, (110, 110, 110))):
            cell = table.rows[r_].cells[i]
            cell.text = ""
            p = cell.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            run = p.add_run(txt)
            run.bold = bold
            run.font.size = Pt(sz)
            run.font.color.rgb = RGBColor(*color)
            tcPr = cell._element.get_or_add_tcPr()
            shd = tcPr.makeelement(qn("w:shd"),
                                   {qn("w:val"): "clear", qn("w:fill"): "E8F5E9"})
            tcPr.append(shd)
    doc.add_paragraph()


