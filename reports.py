def _difficulty_rows(df, mapping):
    """Per-subject stats sorted by mean, highest first. Returns list of
    dicts: subject, count, min, max, mean, median, std."""
    raw = df.attrs.get("raw")
    cols = mapping.get("subject") or []
    out = []
    for col in cols:
        if raw is None or col not in raw.columns:
            continue
        vals = pd.to_numeric(raw[col], errors="coerce").dropna()
        if len(vals) == 0:
            continue
        out.append({
            "subject": col,
            "count": int(len(vals)),
            "min": round(float(vals.min()), 1),
            "max": round(float(vals.max()), 1),
            "mean": round(float(vals.mean()), 1),
            "median": round(float(vals.median()), 1),
            "std": round(float(vals.std(ddof=1)), 1) if len(vals) > 1 else 0.0,
        })
    out.sort(key=lambda d: d["mean"], reverse=True)
    return out


