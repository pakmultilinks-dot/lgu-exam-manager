def _excel_sheet(title: str, report_title: str):
    """Create a workbook with LGU title rows. Returns (wb, ws, next_row)."""
    wb = Workbook()
    ws = wb.active
    ws.title = title[:31]
    ws["A1"] = "Lahore Garrison University"
    ws["A1"].font = _TITLE_FONT
    ws["A2"] = "Examination Department"
    ws["A2"].font = _SUBTITLE_FONT
    if globals().get("_HAS_DEPT_DATA", False):
        dept = globals().get("_ACTIVE_DEPT_LABEL", "All Departments")
        ws["A3"] = f"{report_title}  |  Department: {dept}"
    else:
        ws["A3"] = report_title
    ws["A3"].font = Font(bold=True, size=12)
    return wb, ws, 5  # data starts at row 5


def _excel_table(ws, start_row: int, headers: list, rows: list):
    """Write a styled table starting at start_row. Returns next free row."""
    for ci, h in enumerate(headers, start=1):
        cell = ws.cell(row=start_row, column=ci, value=str(h))
        cell.font = _HEADER_FONT
        cell.fill = _HEADER_FILL
        cell.alignment = Alignment(horizontal="center")
        cell.border = _THIN_BORDER
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row, start=1):
            cell = ws.cell(row=start_row + 1 + ri, column=ci, value=val)
            cell.border = _THIN_BORDER
            if ri % 2 == 1:
                cell.fill = PatternFill(start_color="F0F4F0", fill_type="solid")
    # Auto-width
    for ci in range(1, len(headers) + 1):
        max_len = max(
            [len(str(headers[ci - 1]))] +
            [len(str(r[ci - 1])) if r[ci - 1] is not None else 0 for r in rows],
            default=10,
        )
        ws.column_dimensions[ws.cell(row=1, column=ci).column_letter].width = min(max_len + 4, 40)
    return start_row + 1 + len(rows) + 1


def _sorted(df):
    cgpa = pd.to_numeric(df["_cgpa"], errors="coerce")
    return df.assign(_c=cgpa).sort_values("_c", ascending=False)


def _fmt_cgpa(v):
    return "" if pd.isna(v) else f"{float(v):.2f}"


def _gazette_data(df: pd.DataFrame, mapping: dict):
    """Shared data builder for gazette in all formats."""
    subj_cols = mapping.get("subject") or []
    headers = ["Roll No", "Name"] + list(subj_cols) + ["CGPA", "Status"]
    rows = []
    raw = df.attrs.get("raw")
    for _, row in df.iterrows():
        cells = [row["_roll"], row["_name"]]
        if raw is not None:
            for s in subj_cols:
                v = raw.loc[row.name, s] if s in raw.columns else ""
                cells.append("" if pd.isna(v) else v)
        cells += [_fmt_cgpa(row["_cgpa"]), row["_status"]]
        rows.append(cells)
    stats = compute_stats(df)
    return headers, rows, stats


def _analysis_data(df: pd.DataFrame):
    stats = compute_stats(df)
    summary = [
        ("Average " + stats.get("grade_label", "CGPA"), stats["avg_cgpa"]),
        ("Highest " + stats.get("grade_label", "CGPA"), stats["max_cgpa"]),
        ("Lowest " + stats.get("grade_label", "CGPA"), stats["min_cgpa"]),
    ]
    dist_rows = [[k, v] for k, v in stats["distribution"].items()]
    merit_rows = [[i + 1, m["roll"], m["name"], _fmt_cgpa(m["cgpa"])]
                  for i, m in enumerate(stats["merit"])]
    return summary, dist_rows, merit_rows


