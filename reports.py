def _safe(text) -> str:
    """Strip characters the built-in PDF font cannot render (non latin-1).

    Prevents FPDFUnicodeEncodingException on names like non-Latin scripts.
    """
    if text is None or (isinstance(text, float) and pd.isna(text)):
        return ""
    return str(text).encode("latin-1", errors="replace").decode("latin-1")


