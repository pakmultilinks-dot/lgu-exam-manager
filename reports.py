def _pdf_bar_chart(r, labels, values, title, ylabel="Marks"):
    """Draw a simple vertical bar chart directly with fpdf2 (no image
    rendering). Fast enough for one chart per student on large cohorts."""
    labels = [_safe(str(l)) for l in labels]
    r.set_font("Helvetica", "B", 11)
    r.set_text_color(*LGU_GREEN)
    r.cell(0, 8, _safe(title), align="C", new_x="LMARGIN", new_y="NEXT")
    if not labels or not values or max(values) <= 0:
        r.set_font("Helvetica", "I", 9)
        r.set_text_color(120, 120, 120)
        r.cell(0, 6, "No numeric marks to chart.",
               new_x="LMARGIN", new_y="NEXT")
        r.set_text_color(*DARK)
        return
    x0, w, chart_h = 15, 180, 52
    if r.get_y() + chart_h + 18 > 277:
        r.add_page()
    y0 = r.get_y() + 2
    maxv = max(values)
    n = len(labels)
    slot = w / n
    bar_w = min(slot * 0.62, 24)
    r.set_draw_color(180, 180, 180)
    r.set_line_width(0.3)
    r.line(x0, y0, x0, y0 + chart_h)          # y axis
    r.line(x0, y0 + chart_h, x0 + w, y0 + chart_h)  # x axis
    for i, (lab, val) in enumerate(zip(labels, values)):
        h = max((val / maxv) * chart_h, 1.5)
        xs = x0 + i * slot
        r.set_fill_color(*LGU_GREEN)
        r.rect(xs + (slot - bar_w) / 2, y0 + chart_h - h, bar_w, h, "F")
        r.set_xy(xs, y0 + chart_h - h - 5)
        r.set_font("Helvetica", "", 7)
        r.set_text_color(*DARK)
        r.cell(slot, 4, _safe(str(val)), align="C")
        r.set_xy(xs, y0 + chart_h + 1)
        r.set_font("Helvetica", "", 7)
        r.set_text_color(90, 90, 90)
        r.cell(slot, 4, lab[:16], align="C")
    r.set_xy(10, y0 + chart_h + 7)
    r.set_text_color(*DARK)


