_ACTIVE_DEPT_LABEL = "All Departments"
_HAS_DEPT_DATA = False


def dept_label(df) -> str:
    """Department scope for a report: the single department name if the frame
    covers exactly one, else 'All Departments'."""
    try:
        if df is not None and "_department" in getattr(df, "columns", []):
            vals = [v for v in df["_department"].astype(str).str.strip()
                    .unique().tolist() if v]
            if len(vals) == 1:
                return vals[0]
    except Exception:
        pass
    return "All Departments"


def _set_active_dept(df):
    """Record the department scope for the report about to be generated."""
    global _ACTIVE_DEPT_LABEL, _HAS_DEPT_DATA
    try:
        _HAS_DEPT_DATA = bool(
            df is not None and "_department" in getattr(df, "columns", [])
            and df["_department"].astype(str).str.strip().replace("", pd.NA)
            .notna().any())
    except Exception:
        _HAS_DEPT_DATA = False
    _ACTIVE_DEPT_LABEL = dept_label(df)


class LGUReport(FPDF):
    def __init__(self, title: str):
        super().__init__(orientation="P", unit="mm", format="A4")
        self.report_title = title
        self.set_auto_page_break(True, margin=20)
    def header(self):
        show_dept = globals().get("_HAS_DEPT_DATA", False)
        dept = globals().get("_ACTIVE_DEPT_LABEL", "All Departments")
        bar_h = 31 if show_dept else 26
        self.set_fill_color(*LGU_GREEN)
        self.rect(0, 0, 210, bar_h, "F")
        try:
            lp = _logo_path()
            if os.path.exists(lp):
                self.image(lp, x=186, y=5, w=16)
        except Exception:
            pass
        self.set_xy(10, 6)
        self.set_text_color(*LGU_GOLD)
        self.set_font("Helvetica", "B", 15)
        self.cell(0, 7, "Lahore Garrison University", align="C", new_x="LMARGIN", new_y="NEXT")
        self.set_x(10)
        self.set_font("Helvetica", "", 10)
        self.cell(0, 5, "Examination Department", align="C", new_x="LMARGIN", new_y="NEXT")
        if show_dept:
            self.set_x(10)
            self.set_text_color(*LGU_GOLD)
            self.set_font("Helvetica", "", 9)
            self.cell(0, 5, _safe(f"Department: {dept}"), align="C",
                      new_x="LMARGIN", new_y="NEXT")
        self.set_x(10)
        self.set_text_color(*WHITE)
        self.set_font("Helvetica", "B", 11)
        self.cell(0, 6, self.report_title, align="C", new_x="LMARGIN", new_y="NEXT")
        self.ln(6)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(120, 120, 120)
        self.cell(0, 10,
                  f"Page {self.page_no()}/{{nb}}  |  Generated by LGU Exam Manager - Examination Branch, LGU",
                  align="C")

    def section(self, text: str):
        self.set_font("Helvetica", "B", 12)
        self.set_text_color(*LGU_GREEN)
        self.cell(0, 8, _safe(text), new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(*LGU_GOLD)
        self.set_line_width(0.6)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(3)
        self.set_text_color(*DARK)

    def _wrap_text(self, text, width):
        """Split text into lines that fit within width (mm). Never cuts words
        unless a single word exceeds the width, then breaks the word."""
        text = _safe(text)
        if not text:
            return [""]
        max_w = width - 2  # 1mm padding each side
        words = text.split()
        lines = []
        current = ""
        for word in words:
            # Break an overlong single word into chunks that fit
            while len(word) > 1 and self.get_string_width(word) > max_w:
                k = len(word)
                while k > 1 and self.get_string_width(word[:k]) > max_w:
                    k -= 1
                if current:
                    lines.append(current)
                    current = ""
                lines.append(word[:k])
                word = word[k:]
            test = (current + " " + word).strip()
            if self.get_string_width(test) <= max_w:
                current = test
            else:
                if current:
                    lines.append(current)
                current = word
        if current:
            lines.append(current)
        return lines or [""]

    def _wrapped_row(self, cells, widths, line_h, fill, is_header):
        """Render one table row with wrapping text. Returns nothing; advances y."""
        # 1. Wrap every cell, find tallest
        wrapped = [self._wrap_text(c, w) for c, w in zip(cells, widths)]
        max_lines = max(len(lines) for lines in wrapped)
        row_h = max_lines * line_h
        # 2. Page break if needed
        if self.get_y() + row_h > 275:
            self.add_page()
        x0 = self.l_margin
        y0 = self.get_y()
        # 3. Draw each cell: background + border + vertically-centered text
        for i, (lines, w) in enumerate(zip(wrapped, widths)):
            x = x0 + sum(widths[:i])
            if is_header:
                self.set_fill_color(*LGU_GREEN)
                self.rect(x, y0, w, row_h, "DF")
            elif fill:
                self.set_fill_color(*LIGHT)
                self.rect(x, y0, w, row_h, "DF")
            else:
                self.rect(x, y0, w, row_h, "D")
            text_block_h = len(lines) * line_h
            ty = y0 + (row_h - text_block_h) / 2
            for j, line in enumerate(lines):
                self.set_xy(x, ty + j * line_h)
                self.cell(w, line_h, line, align="C")
        self.set_xy(x0, y0 + row_h)

    def table(self, headers: list, rows: list, widths: list | None = None):
        n = len(headers)
        if widths is None:
            widths = [190 / n] * n
        # Header row
        self.set_font("Helvetica", "B", 8)
        self.set_text_color(*WHITE)
        self._wrapped_row(headers, widths, line_h=7, fill=False, is_header=True)
        # Data rows
        self.set_font("Helvetica", "", 8)
        self.set_text_color(*DARK)
        fill = False
        for row in rows:
            self._wrapped_row(row, widths, line_h=6, fill=fill, is_header=False)
            fill = not fill

    def kv(self, label: str, value):
        self.set_font("Helvetica", "B", 10)
        self.cell(60, 7, _safe(f"{label}:"))
        self.set_font("Helvetica", "", 10)
        self.cell(0, 7, _safe(value), new_x="LMARGIN", new_y="NEXT")


def _wrap_text_for(pdf, text, width):
    """Module-level text wrapper usable with any FPDF instance."""
    text = _safe(text)
    if not text:
        return [""]
    max_w = width - 2
    words = text.split()
    lines = []
    current = ""
    for word in words:
        while len(word) > 1 and pdf.get_string_width(word) > max_w:
            k = len(word)
            while k > 1 and pdf.get_string_width(word[:k]) > max_w:
                k -= 1
            if current:
                lines.append(current)
                current = ""
            lines.append(word[:k])
            word = word[k:]
        test = (current + " " + word).strip()
        if pdf.get_string_width(test) <= max_w:
            current = test
        else:
            if current:
                lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines or [""]


def _wrapped_table_row(pdf, cells, widths, line_h, fill_color=None,
                       text_color=(30, 30, 30), font=("Helvetica", "", 8),
                       align="C", max_y=275, x0=None):
    """Render one wrapping table row on any FPDF instance. Handles page breaks."""
    pdf.set_font(*font)
    pdf.set_text_color(*text_color)
    wrapped = [_wrap_text_for(pdf, c, w) for c, w in zip(cells, widths)]
    max_lines = max(len(lines) for lines in wrapped)
    row_h = max_lines * line_h
    if pdf.get_y() + row_h > max_y:
        pdf.add_page()
    if x0 is None:
        x0 = pdf.l_margin
    y0 = pdf.get_y()
    for i, (lines, w) in enumerate(zip(wrapped, widths)):
        x = x0 + sum(widths[:i])
        if fill_color is not None:
            pdf.set_fill_color(*fill_color)
            pdf.rect(x, y0, w, row_h, "DF")
        else:
            pdf.rect(x, y0, w, row_h, "D")
        text_block_h = len(lines) * line_h
        ty = y0 + (row_h - text_block_h) / 2
        for j, line in enumerate(lines):
            pdf.set_xy(x, ty + j * line_h)
            pdf.cell(w, line_h, line, align=align)
    pdf.set_xy(x0, y0 + row_h)


