def _profile_students(df, mapping, roll_filter=None):
    """Build per-student profile dicts. Marks shown EXACTLY as in the source
    file; the chart uses numeric values only."""
    raw = df.attrs.get("raw")
    cols = mapping.get("subject") or []
    work = df
    if roll_filter is not None:
        work = df[df["_roll"].astype(str) == str(roll_filter)]
    cgpa_num = pd.to_numeric(df["_cgpa"], errors="coerce") if "_cgpa" in df.columns else pd.Series([], dtype=float)
    rank_of = {}
    if len(cgpa_num) and cgpa_num.notna().any():
        ranks = cgpa_num.rank(ascending=False, method="min")
        for idx in df.index:
            if pd.notna(cgpa_num.loc[idx]):
                rank_of[idx] = int(ranks.loc[idx])
    students = []
    for idx, srow in work.iterrows():
        marks = []  # (subject, display_value, numeric_or_nan)
        for c in cols:
            disp, num = "", float("nan")
            if raw is not None and c in raw.columns and idx in raw.index:
                v = raw.at[idx, c]
                if not _blank(v):
                    disp = str(v).strip()
                    num = pd.to_numeric(pd.Series([v]), errors="coerce").iloc[0]
            marks.append((c, disp, num))
        cgpa_disp = ""
        if "_cgpa" in df.columns and not _blank(srow["_cgpa"]):
            cgpa_disp = str(srow["_cgpa"]).strip()
        students.append({
            "roll": str(srow["_roll"]).strip() if "_roll" in df.columns else "",
            "name": str(srow["_name"]).strip() if "_name" in df.columns else "",
            "cgpa": cgpa_disp,
            "rank": rank_of.get(idx),
            "marks": marks,
        })
    return students


