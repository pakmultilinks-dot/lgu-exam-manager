# 4. SESSION COMPARISON (current results vs a previous session file)
# ---------------------------------------------------------------------------
def _comparison_data(df, mapping):
    """Build the comparison dataset. Raises ValueError when no previous
    session has been loaded. Subject matching is by name only and every
    mismatch is reported explicitly instead of guessed."""
    cdf = df.attrs.get("compare_df")
    cmapping = df.attrs.get("compare_mapping")
    if cdf is None or cmapping is None:
        raise ValueError("Load a previous session file first (Session Comparison panel).")
    prev_label = df.attrs.get("compare_label", "Previous session")
    cur_label = df.attrs.get("current_label", "Current session")
    raw = df.attrs.get("raw")
    craw = cdf.attrs.get("raw")

    cur_subj = list(mapping.get("subject") or [])
    prev_subj = list(cmapping.get("subject") or [])

    def subj_mean(frame_raw, col):
        if frame_raw is None or col not in frame_raw.columns:
            return None
        vals = pd.to_numeric(frame_raw[col], errors="coerce").dropna()
        return round(float(vals.mean()), 1) if len(vals) else None

    # match subjects: exact name first, then case-insensitive
    prev_norm = {}
    for s in prev_subj:
        prev_norm.setdefault(str(s).strip().lower(), s)
    matched, used_prev = [], set()
    for s in cur_subj:
        if s in prev_subj:
            matched.append((s, s, "Exact name match"))
            used_prev.add(s)
        else:
            key = str(s).strip().lower()
            if key in prev_norm and prev_norm[key] not in used_prev:
                p = prev_norm[key]
                matched.append((s, p, "Name matches except case/spacing"))
                used_prev.add(p)
    unmatched_cur = [s for s in cur_subj if s not in [m[0] for m in matched]]
    unmatched_prev = [s for s in prev_subj if s not in used_prev]

    shifts = []
    for s, p, how in matched:
        mc, mp = subj_mean(raw, s), subj_mean(craw, p)
        if mc is not None and mp is not None:
            shifts.append({"subject": s, "prev_name": p, "match": how,
                           "current": mc, "previous": mp,
                           "shift": round(mc - mp, 1)})
    shifts.sort(key=lambda d: d["shift"], reverse=True)

    def topper(frame, mp_):
        cg = pd.to_numeric(frame["_cgpa"], errors="coerce") if "_cgpa" in frame.columns else pd.Series([], dtype=float)
        if len(cg) == 0 or not cg.notna().any():
            return None
        i = cg.idxmax()
        return {"roll": str(frame.at[i, "_roll"]).strip(),
                "name": str(frame.at[i, "_name"]).strip(),
                "cgpa": round(float(cg.loc[i]), 2)}

    cur_top, prev_top = topper(df, mapping), topper(cdf, cmapping)

    def grade_mean(frame):
        cg = pd.to_numeric(frame["_cgpa"], errors="coerce") if "_cgpa" in frame.columns else pd.Series([], dtype=float)
        v = cg.dropna()
        return round(float(v.mean()), 2) if len(v) else None

    cur_gm, prev_gm = grade_mean(df), grade_mean(cdf)

    return {
        "cur_label": cur_label, "prev_label": prev_label,
        "n_cur": len(df), "n_prev": len(cdf),
        "shifts": shifts,
        "unmatched_cur": unmatched_cur, "unmatched_prev": unmatched_prev,
        "cur_top": cur_top, "prev_top": prev_top,
        "cur_gm": cur_gm, "prev_gm": prev_gm,
    }


def _comparison_shift_rows(data):
    rows = []
    for d in data["shifts"]:
        s = d["shift"]
        arrow = "up" if s > 0 else ("down" if s < 0 else "same")
        rows.append([d["subject"][:34], d["previous"], d["current"],
                     f"{s:+.1f}", arrow, d["match"]])
    return rows


