# ================= 9. STATISTICAL BREAKDOWN (polished: quartiles) =================

def _stats_data2(df: pd.DataFrame, mapping: dict):
    subj_cols = mapping.get("subject") or []
    raw = df.attrs.get("raw")
    rows = []
    for s in subj_cols:
        if raw is None or s not in raw.columns:
            continue
        vals = pd.to_numeric(raw[s], errors="coerce").dropna()
        if len(vals) == 0:
            continue
        q1 = round(float(vals.quantile(0.25)), 2)
        q3 = round(float(vals.quantile(0.75)), 2)
        rows.append([s, len(vals), round(float(vals.mean()), 2),
                     round(float(vals.median()), 2),
                     round(float(vals.std()), 2) if len(vals) > 1 else 0,
                     q1, q3, round(q3 - q1, 2),
                     round(float(vals.max()), 2), round(float(vals.min()), 2)])
    return rows


