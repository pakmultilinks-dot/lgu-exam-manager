_FATHER_HINTS = ("father", "guardian", "parent", "f_name", "fname", "s/o", "d/o",
                 "son of", "daughter of", "father_name", "guardian_name")


def _dmc_settings(df: pd.DataFrame) -> dict:
    """Settings for the DMC: department/semester/session/declaration_date."""
    default = {"department": "", "semester": "",
               "session": "", "declaration_date": "",
               "topper_count": 3}
    s = df.attrs.get("settings") or {}
    return {**default, **s}


def _dmc_father_col(df: pd.DataFrame, mapping: dict):
    """Find a father/guardian column in the raw data, or None.

    Checks every raw column except the core identity roles. Takes priority
    over the subject list: if a column named like a guardian ended up in
    subjects (auto-mapping), it is still treated as the father column here
    (and excluded from course rows). Never invents: returns the actual
    column, or None (-> shown as em-dash).
    """
    raw = df.attrs.get("raw")
    if raw is None:
        return None
    core = set()
    for k in ("roll", "name", "cgpa", "status"):
        v = mapping.get(k)
        if v:
            core.add(v)
    for c in raw.columns:
        if c in core:
            continue
        cl = str(c).strip().lower()
        if any(h in cl for h in _FATHER_HINTS):
            return c
    return None


def _dmc_cert_no(df: pd.DataFrame, pos: int) -> str:
    """DMC-YYYY-XXXXX certificate number. pos = 1-based position in output."""
    settings = _dmc_settings(df)
    try:
        stamp = pd.to_datetime(settings["declaration_date"])
        year = str(stamp.year) if pd.notna(stamp) else ""
    except Exception:
        year = ""
    return f"DMC-{year}-{pos:05d}" if year else f"DMC-{pos:05d}"


def _dmc_grade_label(df: pd.DataFrame) -> str:
    scale = df.attrs.get("cgpa_scale")
    return {"cgpa4": "CGPA", "cgpa5": "CGPA (5.0 Scale)",
            "cgpa10": "GPA (10.0 Scale)", "percent": "Percentage",
            "marks": "Marks", "grades": "Grade"}.get(scale, "Grade")


def _dmc_scale_rows(df: pd.DataFrame):
    """Grading-scale reference rows for the detected scale, or None.

    Uses the standard HEC letter-grade table (reference only, never applied
    to student data).
    """
    from importer import _GRADE_TO_CGPA
    scale = df.attrs.get("cgpa_scale")
    if scale in ("cgpa4", "cgpa5", "cgpa10", "grades"):
        rows = [[g, f"{v:.1f}"] for g, v in _GRADE_TO_CGPA.items()]
        return ("Standard HEC Grading Scale (Reference)",
                ["Grade", "Grade Point"], rows)
    if scale == "percent":
        return ("Percentage Bands (Reference)",
                ["Percentage", "Division"],
                [["85 - 100", "First Division"],
                 ["70 - 84", "First Division"],
                 ["60 - 69", "Second Division"],
                 ["50 - 59", "Second Division"],
                 ["40 - 49", "Third Division"],
                 ["Below 40", "Fail"]])
    return None


def _dmc_student_rows(df: pd.DataFrame, mapping: dict, row, father_col):
    """Ordered (label, value) pairs for the student information block."""
    settings = _dmc_settings(df)
    father = "-"
    if father_col is not None:
        raw = df.attrs.get("raw")
        try:
            v = raw.loc[row.name, father_col]
            if not (v is None or (isinstance(v, float) and pd.isna(v))
                    or str(v).strip() in ("", "nan")):
                father = str(v).strip()
        except Exception:
            pass
    return [
        ("Registration Number", str(row["_roll"])),
        ("Student Name", str(row["_name"])),
        ("Father / Guardian Name", father),
        ("Program / Department", settings["department"]),
        ("Semester", f"{settings['semester']} {settings['session']}"),
    ]


def _dmc_course_rows(df: pd.DataFrame, mapping: dict, row):
    """[(sr, code, title, marks_str)] - marks shown EXACTLY as in source."""
    subj_cols = mapping.get("subject") or []
    father_col = _dmc_father_col(df, mapping)
    # A guardian column that slipped into subjects is not a course.
    subj_cols = [s for s in subj_cols if s != father_col]
    raw = df.attrs.get("raw")
    out = []
    for i, s in enumerate(subj_cols, start=1):
        code, title = _split_course(s)
        marks = ""
        if raw is not None and s in raw.columns:
            try:
                v = raw.loc[row.name, s]
                if v is None or (isinstance(v, float) and pd.isna(v)):
                    marks = ""
                elif isinstance(v, float) and v.is_integer():
                    marks = str(int(v))
                else:
                    marks = str(v).strip()
            except Exception:
                marks = ""
        out.append([i, code or "-", title, marks])
    return out


