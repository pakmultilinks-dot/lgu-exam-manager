def _gen_ts() -> str:
    """Generation timestamp line used on every report."""
    return "Generated on: " + pd.Timestamp.now().strftime("%d %B %Y, %I:%M %p")


def _pdf_ts(r):
    """Right-aligned generation timestamp (call after add_page)."""
    r.set_font("Helvetica", "I", 8)
    r.set_text_color(130, 130, 130)
    r.cell(0, 5, _safe(_gen_ts()), align="R", new_x="LMARGIN", new_y="NEXT")
    r.set_text_color(*DARK)


def _pdf_stat_box(r, items):
    """Light summary box with centered stat columns. items=[(label, value)].
    Text wraps within columns instead of being cut off."""
    n = len(items)
    if n == 0:
        return
    y0 = r.get_y()
    h = 18
    r.set_fill_color(232, 245, 233)
    r.set_draw_color(*LGU_GOLD)
    r.set_line_width(0.4)
    r.rect(10, y0, 190, h, "DF")
    cw = 190 / n
    for i, (label, value) in enumerate(items):
        x = 10 + i * cw
        r.set_xy(x + 1, y0 + 2)
        r.set_font("Helvetica", "B", 12)
        r.set_text_color(*LGU_GREEN)
        r.multi_cell(cw - 2, 7, _safe(str(value)), align="C")
        r.set_xy(x + 1, y0 + 10)
        r.set_font("Helvetica", "", 8)
        r.set_text_color(90, 90, 90)
        r.multi_cell(cw - 2, 4, _safe(str(label)), align="C")
    r.set_xy(10, y0 + h + 3)
    r.set_text_color(*DARK)


