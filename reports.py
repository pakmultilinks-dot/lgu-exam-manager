# --- 4. Subject-wise Pass Percentage (operator rule: passing marks) ---

def _subject_pass_pct_data(df: pd.DataFrame, mapping: dict):
    """With an operator-set passing mark: per-subject at/above vs below
    counts. Without it: value-neutral marks summary (min/max/mean/median)."""
    rule = _operator_rule(df, "passing_marks")
    subj_cols = mapping.get("subject") or []
    raw = df.attrs.get("raw")
    rows = []
    for s in subj_cols:
        if raw is None or s not in raw.columns:
            continue
        vals = pd.to_numeric(raw[s], errors="coerce").dropna()
        total = len(vals)
        if total == 0:
            continue
        if rule is not None:
            above = int((vals >= rule).sum())
            below = total - above
            pct = round(above / total * 100, 1)
            rows.append([s, total, above, below, f"{pct}%"])
        else:
            rows.append([s, total, _fmt_rule(vals.min()), _fmt_rule(vals.max()),
                         _fmt_rule(vals.mean()),
                         _fmt_rule(vals.median())])
    return rule, rows


