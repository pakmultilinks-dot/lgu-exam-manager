# Layout mirrors the official LGU result gazette:
#   1. Cover page (logo, university, department, "Result Gazette", semester,
#      result declaration date, prepared by Examination Branch)
#   2. Table of contents (SR | SESSION | DEGREE | PAGE NUMBER)
#   3. Per-student RESULT STATEMENT blocks with course tables and SGPA.
#
# DATA INTEGRITY: marks are shown exactly as in the source file. Grades are
# shown ONLY when the source value is itself a letter grade; otherwise "-".
# No conversions, no invented thresholds (relative marking).
import re as _re


def _logo_path() -> str:
    return os.path.join(os.path.dirname(os.path.abspath(__file__)), "lgu-logo.jpg")


def _gazette_settings(df: pd.DataFrame) -> dict:
    default = {"department": "", "semester": "",
               "session": "", "declaration_date": "",
               "topper_count": 3}
    s = df.attrs.get("settings") or {}
    return {**default, **s}


def _fmt_decl_date(ds) -> str:
    """'2026-01-01' -> '01 JANUARY 2026' (official gazette style)."""
    try:
        return pd.to_datetime(ds).strftime("%d %B %Y").upper()
    except Exception:
        return str(ds).upper()


def _split_course(col) -> tuple:
    """'CS-101 Programming Fundamentals' -> ('CS-101', 'Programming Fundamentals')."""
    s = str(col).strip()
    parts = s.split(None, 1)
    if len(parts) == 2:
        code = parts[0]
        if "-" in code or (len(code) <= 10 and code.upper() == code and
                           _re.search(r"[A-Z0-9]", code)):
            return code.upper(), parts[1].strip()
    return "", s


def _detect_session_col(df: pd.DataFrame):
    raw = df.attrs.get("raw")
    if raw is None:
        return None
    for c in raw.columns:
        cl = str(c).lower()
        if any(k in cl for k in ("session", "semester", "batch", "intake", "term")):
            return c
    return None


def _course_marks_grade(v) -> tuple:
    """Return (marks_str, grade_str) without inventing anything.

    Numeric values go to Marks (exact, unmodified). Values that already look
    like letter grades go to Grade. Everything else: marks as-is, grade "-".
    """
    if v is None or (isinstance(v, float) and pd.isna(v)) or str(v).strip() == "":
        return "", "-"
    s = str(v).strip()
    if _re.fullmatch(r"[A-Fa-f][+-]?", s):
        return "", s.upper()
    num = pd.to_numeric(pd.Series([s]), errors="coerce").iloc[0]
    if pd.notna(num):
        return f"{float(num):g}", "-"
    return s, "-"


def _gazette_groups(df: pd.DataFrame, settings: dict):
    """Group students for the table of contents.

    Returns list of (session_label, degree_label, [row_index, ...]).
    """
    sess_col = _detect_session_col(df)
    raw = df.attrs.get("raw")
    if sess_col is not None and raw is not None:
        groups = {}
        order = []
        for idx, row in df.iterrows():
            try:
                sess = str(raw.loc[row.name, sess_col]).strip()
            except Exception:
                sess = ""
            if not sess or sess.lower() == "nan":
                sess = settings["session"]
            if sess not in groups:
                groups[sess] = []
                order.append(sess)
            groups[sess].append(idx)
        return [(s, settings["department"], groups[s]) for s in order]
    # Single group: everything in one block
    return [(settings["session"], settings["department"], list(df.index))]


